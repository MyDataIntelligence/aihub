/**
 * Everything the old AI Context Hub (v1.x/2.x: Kotlin core, `hub` CLI package, VS Code extension, agent hooks) put on a
 * machine, found only by proof of ownership (a marker, a known generated shape, an exact name), and its removal.
 * The inventory and the recognition rule of every item are in docs/legacy-removal.md; keep both in step.
 */
export type Group = "VS Code extension" | "CLI package" | "Skills, agents and rules" | "Hooks" | "Registry" | "Files and data" | "Settings" | "Per-repo leftovers";
export const GROUPS: Group[] = ["VS Code extension", "CLI package", "Skills, agents and rules", "Hooks", "Registry", "Files and data", "Settings", "Per-repo leftovers"];

export interface Item {
  group: Group;
  /** The client the item belongs to (copilot, opencode, codex, vscode, git ...), shown in front of the line. */
  client?: string;
  what: string;
  where: string;
  /** User data of the old Hub (settings, caches, logs): kept by --keep-data. */
  data?: boolean;
  /** An `aiContextHub.*` key in a VS Code settings file: kept by --keep-settings. */
  settings?: boolean;
  apply: () => void;
}

export interface Scan {
  items: Item[];
  /** Look-alikes and files that are not provably Hub-owned: found, named, and left alone. */
  kept: string[];
  /** Steps that could not be checked (no `code` on the PATH, no `reg`). */
  notes: string[];
}

export interface Run {
  status: number;
  stdout: string;
  stderr: string;
}

export interface LegacyDeps {
  env: NodeJS.ProcessEnv;
  cwd: string;
  /** Runs code/reg (tests inject fakes); git is always the real one. */
  spawn?: (cmd: string, args: string[], cwd: string, timeoutMs: number) => Run;
  repos: string[];
  keepData?: boolean;
}

