// ------------------------------------------------------------------------------------------------ JSONC editing

interface Member {
  key: string;
  keyStart: number;
  valueEnd: number;
  comma: number;
}

/** The members of the top-level object of a JSONC text (comments and trailing commas allowed). */
export function topLevelMembers(t: string): Member[] {
  const out: Member[] = [];
  const n = t.length;
  let i = t.charCodeAt(0) === 0xfeff ? 1 : 0;
  const skip = () => {
    while (i < n) {
      if (/\s/.test(t[i])) i++;
      else if (t.startsWith("//", i)) while (i < n && t[i] !== "\n") i++;
      else if (t.startsWith("/*", i)) {
        const j = t.indexOf("*/", i + 2);
        i = j < 0 ? n : j + 2;
      } else break;
    }
  };
  const str = (): string => {
    const s = i;
    i++;
    while (i < n && t[i] !== '"') i += t[i] === "\\" ? 2 : 1;
    i++;
    try {
      return JSON.parse(t.slice(s, i)) as string;
    } catch {
      return t.slice(s, i);
    }
  };
  const value = () => {
    if (t[i] === '"') return void str();
    if (t[i] === "{" || t[i] === "[") {
      let depth = 0;
      while (i < n) {
        const c = t[i];
        if (c === '"') {
          str();
          continue;
        }
        if (t.startsWith("//", i) || t.startsWith("/*", i)) {
          skip();
          continue;
        }
        if (c === "{" || c === "[") depth++;
        if (c === "}" || c === "]") depth--;
        i++;
        if (depth === 0) return;
      }
      return;
    }
    while (i < n && !/[\s,}\]]/.test(t[i]) && !t.startsWith("//", i) && !t.startsWith("/*", i)) i++;
  };
  skip();
  if (t[i] !== "{") return out;
  i++;
  for (;;) {
    skip();
    if (i >= n || t[i] === "}") break;
    if (t[i] === ",") {
      i++;
      continue;
    }
    if (t[i] !== '"') break;
    const keyStart = i;
    const key = str();
    skip();
    if (t[i] !== ":") break;
    i++;
    skip();
    value();
    const valueEnd = i;
    skip();
    let comma = -1;
    if (t[i] === ",") {
      comma = i;
      i++;
    }
    out.push({ key, keyStart, valueEnd, comma });
  }
  return out;
}

/** Removes the top-level members whose key matches; everything else (comments, order, indentation) stays. */
export function removeTopLevelKeys(text: string, match: (key: string) => boolean): { text: string; removed: string[] } {
  const removed: string[] = [];
  for (;;) {
    const m = topLevelMembers(text).find((x) => match(x.key));
    if (!m) return { text, removed };
    removed.push(m.key);
    let start = m.keyStart;
    let end = m.comma >= 0 ? m.comma + 1 : m.valueEnd;
    let lineStart = start;
    while (lineStart > 0 && (text[lineStart - 1] === " " || text[lineStart - 1] === "\t")) lineStart--;
    const wholeLine = lineStart === 0 || text[lineStart - 1] === "\n";
    let tail = end;
    while (tail < text.length && (text[tail] === " " || text[tail] === "\t")) tail++;
    if (wholeLine && (tail >= text.length || text[tail] === "\n" || text[tail] === "\r")) {
      start = lineStart;
      end = text[tail] === "\r" && text[tail + 1] === "\n" ? tail + 2 : tail < text.length ? tail + 1 : tail;
    }
    let cut = text.slice(0, start) + text.slice(end);
    if (m.comma < 0) {
      // The last member went: the comma of the member before it must go too.
      const all = topLevelMembers(text);
      const before = all[all.findIndex((x) => x.keyStart === m.keyStart) - 1];
      if (before && before.comma >= 0 && before.comma < start) cut = text.slice(0, before.comma) + text.slice(before.comma + 1, start) + text.slice(end);
    }
    text = cut;
  }
}

// ------------------------------------------------------------------------------------------------ small helpers

function git(cwd: string, args: string[]): string {
  const r = spawnSync("git", args, { cwd, encoding: "utf8" });
  return r.status === 0 ? (r.stdout ?? "").trim() : "";
}

function gitPath(root: string, what: string): string {
  const p = git(root, ["rev-parse", "--git-path", what]);
  return p ? resolve(root, p) : "";
}

function tracked(root: string, rel: string): boolean {
  return git(root, ["ls-files", "--", rel]) !== "";
}

/** The text without the Hub block, or null when the file has none. A front matter alone left behind counts as empty. */
export function withoutBlock(text: string): string | null {
  const re = new RegExp(`(\\r?\\n){0,2}${BLOCK_START}[\\s\\S]*?${BLOCK_END}(\\r?\\n)?`);
  return re.test(text) ? text.replace(re, "\n") : null;
}

const onlyFrontMatter = (text: string) => text.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "").trim() === "";

function newPackOwns(dir: string, rel: string): boolean {
  return rel.replace(/\\/g, "/") in readManifest(dir).files;
}

// ------------------------------------------------------------------------------------------------ scan

export function scan(deps: LegacyDeps): Scan {
  const { env } = deps;
  const platform = env[PLATFORM_ENV] || process.platform;
  const home = env.HOME || env.USERPROFILE || homedir();
  const localAppData = env.LOCALAPPDATA;
  const out: Scan = { items: [], kept: [], notes: [] };
  const add = (i: Item) => out.items.push(i);
  const exec = (cmd: string, args: string[]): Run => {
    if (deps.spawn) return deps.spawn(cmd, args, deps.cwd, 120000);
    const winShell = platform === "win32" && (cmd === "code" || cmd.toLowerCase().endsWith(".cmd"));
    const r = spawnSync(winShell ? [cmd, ...args.map((a) => (/[\s"]/.test(a) ? `"${a}"` : a))].join(" ") : cmd, winShell ? [] : args, { encoding: "utf8", shell: winShell, timeout: 120000 });
    return { status: r.error ? 127 : (r.status ?? 1), stdout: r.stdout ?? "", stderr: r.stderr ?? (r.error ? String(r.error) : "") };
  };

  const copilotHome = env.COPILOT_HOME || join(home, ".copilot");
  const opencodeHomes = [...new Set([env.OPENCODE_CONFIG_DIR, join(env.XDG_CONFIG_HOME || join(home, ".config"), "opencode")].filter((x): x is string => !!x).map((x) => resolve(x)))];
  const codexHome = env.CODEX_HOME || join(home, ".codex");
  const cliHome = env.AIHUB_CLI_HOME || (localAppData ? join(localAppData, "AIContextHub", "cli") : join(home, ".aihub", "cli"));
  const hubRoots = [...(localAppData ? [join(localAppData, "AIContextHub")] : [])];
  const dotAihub = join(home, ".aihub");

  // ---- the old CLI registry names repositories the old Hub worked in (read before the CLI package is removed)
  const repoRoots = new Set<string>();
  const addRepoCandidate = (dir: string) => {
    if (!dir || !isDir(dir)) return;
    repoRoots.add(resolve(dir));
  };
  try {
    const reg = JSON.parse(read(join(cliHome, "repos.json"))) as { repos?: Record<string, { root?: string }> };
    for (const e of Object.values(reg.repos ?? {})) if (e?.root) addRepoCandidate(e.root);
  } catch {
    /* no old registry */
  }
  for (const given of deps.repos) {
    const dir = resolve(deps.cwd, given);
    addRepoCandidate(dir);
    for (const name of list(dir)) {
      const child = join(dir, name);
      if (isDir(child) && (existsSync(join(child, ".git")) || isDir(join(child, ".aihub")))) addRepoCandidate(child);
    }
  }
  if (!deps.repos.length) {
    const top = git(deps.cwd, ["rev-parse", "--show-toplevel"]);
    if (top) addRepoCandidate(top);
  }

  // ---- 1. VS Code extension (and the Worktree Maker the old bundle installed)
  const codeBin = env[CODE_BIN_ENV] || "code";
  let codeArgs: string[] = [];
  try {
    if (env[CODE_ARGS_ENV]) codeArgs = JSON.parse(env[CODE_ARGS_ENV]!) as string[];
  } catch {
    out.notes.push(`${CODE_ARGS_ENV} is not a JSON array of strings: ignored`);
  }
  const listed = exec(codeBin, [...codeArgs, "--list-extensions", "--show-versions"]);
  if (listed.status !== 0) {
    out.notes.push(`VS Code extension: "${codeBin}" did not answer (exit ${listed.status}); extensions were not checked. Uninstall FerronHooi.ai-context-hub below 3.0.0 in the Extensions view, or put code on the PATH and run again.`);
  } else {
    for (const line of listed.stdout.split(/\r?\n/)) {
      const m = /^([^@\s]+)@(\S+)$/.exec(line.trim());
      if (!m) continue;
      const [, id, version] = m;
      const lower = id.toLowerCase();
      const major = Number(/^\d+/.exec(version)?.[0] ?? "0");
      let why = "";
      if (lower === OLD_EXTENSION_ID.toLowerCase()) {
        if (major >= 3) out.kept.push(`${id}@${version}: the new aihub extension (3.x), kept`);
        else why = "the old AI Context Hub extension (below 3.0.0)";
      } else if (FORMER_EXTENSION_IDS.includes(lower)) why = lower === "ferron.worktree-maker" ? "Worktree Maker, installed by the old AI Context Hub bundle" : "the old extension id of AI Context Hub";
      if (why) add({ group: "VS Code extension", client: "vscode", what: `uninstall ${id}@${version} (${why})`, where: codeBin, apply: () => {
        const r = exec(codeBin, [...codeArgs, "--uninstall-extension", id]);
        if (r.status !== 0) throw new Error(`code --uninstall-extension ${id} failed (exit ${r.status}): ${(r.stderr || r.stdout).trim().split("\n")[0]}`);
      } });
    }
  }

  // ---- VS Code user data folders: leftover settings keys and the old extension's global storage
  const userDataDirs: string[] = [];
  const argAt = codeArgs.indexOf("--user-data-dir");
  if (argAt >= 0 && codeArgs[argAt + 1]) userDataDirs.push(resolve(codeArgs[argAt + 1]));
  else
    for (const product of ["Code", "Code - Insiders", "VSCodium"]) {
      const base = platform === "win32" ? env.APPDATA : platform === "darwin" ? join(home, "Library", "Application Support") : env.XDG_CONFIG_HOME || join(home, ".config");
      if (base) userDataDirs.push(join(base, product));
    }
  const settingsFiles = userDataDirs.map((d) => join(d, "User", "settings.json"));
  for (const root of repoRoots) settingsFiles.push(join(root, ".vscode", "settings.json"));
  for (const file of settingsFiles) {
    if (!isFile(file)) continue;
    let text: string;
    try {
      text = read(file);
    } catch {
      continue;
    }
    const keys = topLevelMembers(text).map((m) => m.key).filter((k) => k.startsWith(SETTINGS_PREFIX));
    if (!keys.length) continue;
    add({ group: "Settings", client: "vscode", settings: true, what: `remove ${keys.length} old setting(s): ${keys.join(", ")}`, where: file, apply: () => {
      const cut = removeTopLevelKeys(read(file), (k) => k.startsWith(SETTINGS_PREFIX));
      writeFileSync(file, cut.text, "utf8");
    } });
  }
  for (const dir of userDataDirs)
    for (const id of [OLD_EXTENSION_ID, ...FORMER_EXTENSION_IDS]) {
      const storage = join(dir, "User", "globalStorage", id);
      const found = [storage, storage.toLowerCase()].find((p) => isDir(p));
      if (found) add({ group: "Files and data", client: "vscode", data: true, what: `delete the global storage of ${id}`, where: found, apply: () => rmSync(found, { recursive: true, force: true }) });
    }

  // ---- 2. CLI package (the files of the zip) and 3. the data next to it
  // Also a half-removed package (an earlier run stopped on a locked jar) still counts: the jar alone is enough.
  const cliJar = join(cliHome, "lib", "hub-standalone.jar");
  const cliPackage = (isFile(join(cliHome, "VERSION")) && (isFile(join(cliHome, "hub.ps1")) || isFile(join(cliHome, "hub")))) || isFile(cliJar);
  if (cliPackage) {
    const version = isFile(join(cliHome, "VERSION")) ? read(join(cliHome, "VERSION")).trim() : "(partly removed)";
    add({ group: "CLI package", client: "hub", what: `delete the hub CLI package ${version} (hub, hub.cmd, hub.ps1, lib\\hub-standalone.jar, runtime, skills, templates); a running old Hub core of this package is stopped first`, where: cliHome, apply: () => {
      // Only java processes running exactly this package's jar (the old Hub core); nothing else.
      if (process.platform === "win32") {
        const ps = `Get-CimInstance Win32_Process -Filter "Name='java.exe'" | Where-Object { $_.CommandLine -like '*${cliJar.replace(/'/g, "''")}*' } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force }`;
        exec("powershell", ["-NoProfile", "-Command", ps]);
      } else exec("pkill", ["-f", cliJar]);
      for (const name of CLI_PACKAGE_NAMES) rmSync(join(cliHome, name), { recursive: true, force: true, maxRetries: 5, retryDelay: 300 });
    } });
  }
  const dataEntries: string[] = [];
  if (isDir(cliHome) && (cliPackage || list(cliHome).some((n) => ["repos.json", "run", "logs"].includes(n))))
    for (const name of list(cliHome)) if (!CLI_PACKAGE_NAMES.includes(name)) dataEntries.push(join(cliHome, name));
  for (const root of hubRoots)
    for (const name of list(root)) {
      const full = join(root, name);
      if (same(full, cliHome)) continue;
      dataEntries.push(full);
    }
  for (const name of DOT_AIHUB_DIRS) {
    const full = join(dotAihub, name);
    if (isDir(full) && !same(full, cliHome) && !dataEntries.some((d) => same(d, full))) dataEntries.push(full);
  }
  const hubSettings = join(dotAihub, "config", "hub-settings.json");
  if (isFile(hubSettings)) dataEntries.push(hubSettings);
  const hooksFolders = [join(localAppData ?? "", "AIContextHub", "standalone", "hooks"), join(dotAihub, "standalone", "hooks")].filter((p) => isDir(p));
  for (const e of dataEntries) {
    // A link (symlink or junction, possibly dangling) is removed as a link: never followed, never stat'ed through.
    let link = false;
    try { link = lstatSync(e).isSymbolicLink(); } catch { continue; }
    if (link) { add({ group: "Files and data", client: "hub", data: true, what: `delete link ${basename(e)} (the link only, not what it points to)`, where: e, apply: () => { try { unlinkSync(e); } catch { rmdirSync(e); } } }); continue; }
    if (!existsSync(e)) continue;
    add({ group: "Files and data", client: "hub", data: true, what: `delete ${isDir(e) ? "folder" : "file"} ${basename(e)} (${isDir(e) ? list(e).length + " entries" : statSync(e).size + " bytes"})`, where: e, apply: () => rmSync(e, { recursive: true, force: true }) });
  }

  // ---- 4. skills, agents and rules per client
  const skillsOf = (client: string, home: string) => {
    const skills = join(home, "skills");
    for (const name of list(skills)) {
      if (!/^aihub-/i.test(name)) continue;
      const dir = join(skills, name);
      const file = join(dir, "SKILL.md");
      if (!isFile(file)) continue;
      if (newPackOwns(skills, `${name}/SKILL.md`)) continue;
      if (!GENERATED_BY.test(read(file))) {
        out.kept.push(`${file}: named like an old Hub skill but without the Hub's generated-by / aihub-version marker, so it is yours`);
        continue;
      }
      const extras = list(dir).filter((n) => n !== "SKILL.md");
      if (extras.length) out.kept.push(`${dir}: also holds ${extras.join(", ")}, which are not the Hub's; only SKILL.md goes`);
      add({ group: "Skills, agents and rules", client, what: `delete skill ${name}`, where: file, apply: () => {
        unlinkSync(file);
        rmDirIfEmpty(dir);
      } });
    }
  };
  const instructionsFile = (client: string, file: string) => {
    if (!isFile(file)) return;
    const text = read(file);
    const rest = withoutBlock(text);
    if (rest === null) return void out.kept.push(`${file}: has the Hub's file name but no Hub block, so it is yours`);
    if (onlyFrontMatter(rest) || rest.trim() === "") add({ group: "Skills, agents and rules", client, what: "delete the Hub instructions file", where: file, apply: () => unlinkSync(file) });
    else add({ group: "Skills, agents and rules", client, what: "remove the Hub block from the instructions file (your text stays)", where: file, apply: () => writeFileSync(file, (withoutBlock(read(file)) ?? read(file)).trim() + "\n", "utf8") });
  };
  skillsOf("copilot", copilotHome);
  const agentFile = join(copilotHome, "agents", "hub.agent.md");
  if (isFile(agentFile)) {
    if (/^name:\s*hub\s*$/m.test(read(agentFile)) && HUB_AGENT_MARK.test(read(agentFile))) add({ group: "Skills, agents and rules", client: "copilot", what: "delete the hub agent", where: agentFile, apply: () => unlinkSync(agentFile) });
    else out.kept.push(`${agentFile}: a hub agent without the Hub's generated header, so it is yours`);
  }
  const otherAgents: Array<[string, string]> = [
    ["codex", join(codexHome, "agents", "hub.toml")],
    ["claude", join(env.CLAUDE_CONFIG_DIR || join(home, ".claude"), "agents", "hub.md")],
  ];
  for (const [client, f] of otherAgents) {
    if (!isFile(f)) continue;
    if (HUB_AGENT_MARK.test(read(f))) add({ group: "Skills, agents and rules", client, what: "delete the hub agent", where: f, apply: () => unlinkSync(f) });
    else out.kept.push(`${f}: a hub agent without the Hub's generated header, so it is yours`);
  }
  instructionsFile("copilot", join(copilotHome, "instructions", "ai-context-hub.instructions.md"));
  for (const oc of opencodeHomes) {
    skillsOf("opencode", oc);
    let hubAgentIsOurs = false;
    for (const name of ["hub.md", "hub-hard.md"]) {
      const f = join(oc, "agents", name);
      if (!isFile(f)) continue;
      if (HUB_AGENT_MARK.test(read(f))) {
        if (name === "hub.md") hubAgentIsOurs = true;
        add({ group: "Skills, agents and rules", client: "opencode", what: `delete the ${name.replace(".md", "")} agent`, where: f, apply: () => unlinkSync(f) });
      } else out.kept.push(`${f}: an agent of that name without the Hub's generated header, so it is yours`);
    }
    const oneAgent = join(oc, "agent", "hub.md");
    if (isFile(oneAgent) && HUB_AGENT_MARK.test(read(oneAgent))) add({ group: "Skills, agents and rules", client: "opencode", what: "delete the hub agent (agent/ folder)", where: oneAgent, apply: () => unlinkSync(oneAgent) });
    const rules = join(oc, "AGENTS.md");
    if (isFile(rules)) {
      const rest = withoutBlock(read(rules));
      if (rest !== null)
        add({ group: "Skills, agents and rules", client: "opencode", what: rest.trim() ? "remove the Hub rules block (your text stays)" : "delete AGENTS.md (it held only the Hub rules block)", where: rules, apply: () => {
          const after = withoutBlock(read(rules)) ?? "";
          if (after.trim()) writeFileSync(rules, after.trim() + "\n", "utf8");
          else unlinkSync(rules);
        } });
    }
    for (const name of ["opencode.jsonc", "opencode.json"]) {
      const config = join(oc, name);
      if (!isFile(config)) continue;
      const text = read(config);
      const edited = editOpencodeConfig(text, hubAgentIsOurs || !isFile(join(oc, "agents", "hub.md")));
      if (edited.changes.length)
        add({ group: "Skills, agents and rules", client: "opencode", what: edited.deleteFile ? `delete ${name} (the Hub created it: ${edited.changes.join(", ")})` : `remove ${edited.changes.join(", ")} from ${name}`, where: config, apply: () => {
          const again = editOpencodeConfig(read(config), true);
          if (again.deleteFile) unlinkSync(config);
          else writeFileSync(config, again.text, "utf8");
        } });
      else if (/"default_agent"\s*:\s*"hub"/.test(text)) out.kept.push(`${config}: default_agent "hub" points at an agent that is not the Hub's, so it is yours`);
    }
  }

  // ---- 5. hooks per client
  const copilotHooks = join(copilotHome, "hooks", "aihub.json");
  if (isFile(copilotHooks)) {
    let ours = false;
    try {
      const j = JSON.parse(read(copilotHooks)) as { hooks?: Record<string, Array<Record<string, unknown>>> };
      const cmds = Object.values(j.hooks ?? {}).flatMap((g) => g.flatMap((h) => [h.bash, h.powershell].filter((c): c is string => typeof c === "string")));
      ours = cmds.length > 0 && cmds.every((c) => COPILOT_HOOK_COMMAND.test(c));
    } catch {
      /* not JSON */
    }
    if (ours) add({ group: "Hooks", client: "copilot", what: "delete the Hub hooks (Copilot CLI and VS Code Copilot Chat read this file)", where: copilotHooks, apply: () => unlinkSync(copilotHooks) });
    else out.kept.push(`${copilotHooks}: has the Hub's file name but runs other commands, so it is yours`);
  }
  const codexHooks = join(codexHome, "hooks.json");
  if (isFile(codexHooks)) {
    const cut = withoutCodexEntries(read(codexHooks));
    if (cut && cut.removed > 0)
      add({ group: "Hooks", client: "codex", what: `remove ${cut.removed} Hub hook entr${cut.removed === 1 ? "y" : "ies"} (your own hooks stay)`, where: codexHooks, apply: () => {
        const again = withoutCodexEntries(read(codexHooks));
        if (!again) return;
        if (again.empty) unlinkSync(codexHooks);
        else writeFileSync(codexHooks, again.text, "utf8");
      } });
  }
  for (const oc of opencodeHomes) {
    for (const folder of ["plugin", "plugins"]) {
      const f = join(oc, folder, "aihub.js");
      if (!isFile(f)) continue;
      if (/AI Context Hub plugin for opencode \(managed/.test(read(f))) add({ group: "Hooks", client: "opencode", what: "delete the Hub plugin", where: f, apply: () => {
        unlinkSync(f);
        rmDirIfEmpty(dirname(f));
      } });
      else out.kept.push(`${f}: a plugin of that name without the Hub's header, so it is yours`);
    }
    const story = join(oc, "command", "story-run.md");
    if (isFile(story)) {
      const t = read(story);
      if (/The developer said: \$ARGUMENTS\s*$/.test(t) && !/<!-- aihub /.test(t) && !newPackOwns(dirname(story), "story-run.md")) add({ group: "Hooks", client: "opencode", what: "delete the Hub /story-run command", where: story, apply: () => {
        unlinkSync(story);
        rmDirIfEmpty(dirname(story));
      } });
    }
  }
  for (const folder of hooksFolders) {
    for (const name of ["hub-hook", "hub-hook.cmd", "hub-push-guard", "hub-push-guard.ps1"]) {
      const f = join(folder, name);
      if (isFile(f)) add({ group: "Hooks", client: "hub", what: `delete the hook runner ${name}`, where: f, apply: () => unlinkSync(f) });
    }
    for (const name of list(folder).filter((n) => !["hub-hook", "hub-hook.cmd", "hub-push-guard", "hub-push-guard.ps1"].includes(n)))
      add({ group: "Files and data", client: "hub", data: true, what: `delete ${name} in the hooks folder`, where: join(folder, name), apply: () => rmSync(join(folder, name), { recursive: true, force: true }) });
  }

  // ---- 6. registry (Windows): the user PATH entry of the CLI folder, a Run value that starts something of the Hub
  if (platform === "win32") {
    const q = exec("reg", ["query", "HKCU\\Environment", "/v", "Path"]);
    const m = q.status === 0 ? /^\s*Path\s+(REG_\w+)\s+(.*)$/im.exec(q.stdout) : null;
    if (m) {
      const [, type, value] = m;
      const wanted = [cliHome, "%LOCALAPPDATA%\\AIContextHub\\cli"].map((x) => x.replace(/[\\/]+$/, "").toLowerCase());
      const parts = value.split(";");
      const keep = parts.filter((p) => !wanted.includes(p.trim().replace(/[\\/]+$/, "").toLowerCase()));
      if (keep.length !== parts.length)
        add({ group: "Registry", client: "windows", what: "remove the CLI folder from the user PATH", where: "HKCU\\Environment\\Path", apply: () => {
          const r = exec("reg", ["add", "HKCU\\Environment", "/v", "Path", "/t", type, "/d", keep.join(";"), "/f"]);
          if (r.status !== 0) throw new Error(`reg add HKCU\\Environment\\Path failed (exit ${r.status}): ${r.stderr.trim()}`);
        } });
    } else if (q.status !== 0) out.notes.push("Registry: reg.exe did not answer for HKCU\\Environment; the user PATH was not checked.");
    const run = exec("reg", ["query", "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run"]);
    if (run.status === 0)
      for (const line of run.stdout.split(/\r?\n/)) {
        const r = /^\s+(\S.*?)\s+REG_\w+\s+(.*)$/.exec(line);
        if (r && /AIContextHub/i.test(r[2])) add({ group: "Registry", client: "windows", what: `delete the autostart value ${r[1]}`, where: `HKCU\\...\\Run\\${r[1]}`, apply: () => {
          const d = exec("reg", ["delete", "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run", "/v", r[1], "/f"]);
          if (d.status !== 0) throw new Error(`reg delete failed (exit ${d.status})`);
        } });
      }
  }

  // ---- 7. per-repo leftovers
  const ownHomes = [join(home, ".aihub"), env.AIHUB_HOME].filter((x): x is string => !!x);
  for (const root of repoRoots) scanRepo(root, out, ownHomes);

  return out;
}

