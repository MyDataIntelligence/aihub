/** opencode.json(c): the default_agent "hub", the "aihub-*": "deny" skill rule; the exact text the old Hub inserted. */
export function editOpencodeConfig(text: string, hubAgentIsOurs: boolean): { text: string; changes: string[]; deleteFile: boolean } {
  const changes: string[] = [];
  const bareOf = (t: string) => t.replace(/\s/g, "");
  const empty = (t: string) => bareOf(t) === "{}" || bareOf(t) === '{"$schema":"https://opencode.ai/config.json"}';
  let cfg: Record<string, any> | undefined;
  try {
    cfg = JSON.parse(text.replace(/^﻿/, "")) as Record<string, any>;
  } catch {
    cfg = undefined;
  }
  if (cfg && typeof cfg === "object" && !Array.isArray(cfg)) {
    // Plain JSON (the old installer's own output, or a file the new aihub rewrote): edit it structurally.
    if (hubAgentIsOurs && cfg.default_agent === "hub") {
      delete cfg.default_agent;
      changes.push('"default_agent": "hub"');
    }
    if (cfg.permission?.skill?.["aihub-*"] === "deny") {
      delete cfg.permission.skill["aihub-*"];
      if (Object.keys(cfg.permission.skill).length === 0) delete cfg.permission.skill;
      if (Object.keys(cfg.permission).length === 0) delete cfg.permission;
      changes.push('the "aihub-*": "deny" skill rule');
    }
    const next = JSON.stringify(cfg, null, 2) + "\n";
    return { text: changes.length ? next : text, changes, deleteFile: changes.length > 0 && empty(next) };
  }
  // Comments or trailing commas: only the exact text the old installer inserted is cut, so the rest stays as written.
  let next = text;
  if (hubAgentIsOurs) {
    const cut = next.replace(/,(\n  "default_agent": "hub")(?=\s*\})/, "").replace(/\n  "default_agent": "hub",?/, "");
    if (cut !== next) {
      next = cut;
      changes.push('"default_agent": "hub"');
    }
  }
  for (const re of [/\n  "permission": \{"skill": \{"aihub-\*": "deny"\}\},?/, /\n    "skill": \{"aihub-\*": "deny"\},?/, /"aihub-\*": "deny"(, )?/]) {
    const cut = next.replace(re, "");
    if (cut !== next) {
      next = cut;
      changes.push('the "aihub-*": "deny" skill rule');
      break;
    }
  }
  if (changes.length && !/,\s*\}/.test(text)) next = next.replace(/,(\s*\})/g, "$1");
  return { text: next, changes, deleteFile: changes.length > 0 && empty(next) };
}

/** Codex hooks.json without the Hub's entries; null when the file is not valid JSON (then it is never touched). */
export function withoutCodexEntries(text: string): { text: string; removed: number; empty: boolean } | null {
  let root: Record<string, unknown>;
  try {
    root = JSON.parse(text) as Record<string, unknown>;
  } catch {
    return null;
  }
  if (!root || typeof root !== "object" || Array.isArray(root)) return null;
  const hooks = root.hooks as Record<string, unknown> | undefined;
  let removed = 0;
  if (hooks && typeof hooks === "object") {
    for (const event of Object.keys(hooks)) {
      const groups = hooks[event];
      if (!Array.isArray(groups)) continue;
      const kept = groups.filter((g) => {
        const inner = (g as { hooks?: unknown[] })?.hooks;
        const ours = Array.isArray(inner) && inner.some((h) => ["command", "commandWindows"].some((k) => typeof (h as Record<string, unknown>)?.[k] === "string" && OWN_HOOK_COMMAND.test((h as Record<string, string>)[k])));
        if (ours) removed++;
        return !ours;
      });
      if (kept.length === 0) delete hooks[event];
      else hooks[event] = kept;
    }
    if (Object.keys(hooks).length === 0) delete root.hooks;
  }
  return { text: JSON.stringify(root, null, 2) + "\n", removed, empty: Object.keys(root).length === 0 };
}

/** info/exclude without the lines the old Hub wrote: each Hub comment and the Hub entries that follow it. */
export function cleanExclude(text: string): { text: string; removed: string[] } {
  const lines = text.split(/\r?\n/);
  const out: string[] = [];
  const removed: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (EXCLUDE_COMMENTS.includes(lines[i].trim())) {
      removed.push(lines[i].trim());
      while (i + 1 < lines.length && EXCLUDE_LINE.test(lines[i + 1].trim())) {
        removed.push(lines[i + 1].trim());
        i++;
      }
      continue;
    }
    out.push(lines[i]);
  }
  return { text: out.join("\n"), removed };
}

function stripHookBlock(text: string, begin: string, end: string): string | null {
  const s = text.indexOf(begin);
  const e = s < 0 ? -1 : text.indexOf(end, s);
  if (s < 0 || e < 0) return null;
  const lineStart = text.lastIndexOf("\n", s) + 1;
  const after = text.indexOf("\n", e);
  return text.slice(0, lineStart) + (after < 0 ? "" : text.slice(after + 1));
}

function scanRepo(root: string, out: Scan, ownHomes: string[]) {
  const add = (i: Item) => out.items.push(i);
  const isRepo = existsSync(join(root, ".git"));
  const isTracked = (rel: string) => isRepo && tracked(root, rel);
  const aihub = join(root, ".aihub");
  if (isDir(aihub)) {
    if (ownHomes.some((h) => same(h, aihub)) || list(aihub).some((n) => NEW_AIHUB_ENTRIES.test(n))) out.kept.push(`${aihub}: this is the new aihub's own home (events, Fabric state), so it is never removed`);
    else if (isTracked(".aihub")) out.kept.push(`${aihub}: git tracks files in it, so it is the team's`);
    else add({ group: "Per-repo leftovers", client: "git", data: true, what: "delete the .aihub folder (old Hub state, logs, scratch files)", where: aihub, apply: () => rmSync(aihub, { recursive: true, force: true }) });
  }
  if (!isRepo) return;
  const skills = join(root, ".github", "skills");
  for (const name of list(skills).filter((n) => /^aihub-/i.test(n))) {
    const file = join(skills, name, "SKILL.md");
    if (!isFile(file)) continue;
    if (!GENERATED_BY.test(read(file))) out.kept.push(`${file}: named like an old Hub skill without the Hub marker, so it is yours`);
    else if (isTracked(`.github/skills/${name}/SKILL.md`)) out.kept.push(`${file}: tracked by git, so it is the team's copy`);
    else add({ group: "Per-repo leftovers", client: "git", what: `delete skill ${name}`, where: file, apply: () => {
      unlinkSync(file);
      rmDirIfEmpty(dirname(file));
      rmDirIfEmpty(skills);
    } });
  }
  for (const name of HUB_IDEA_FILES) {
    const f = join(root, ".idea", name);
    if (!isFile(f)) continue;
    if (isTracked(`.idea/${name}`)) out.kept.push(`${f}: tracked by git, so it is the team's`);
    else add({ group: "Per-repo leftovers", client: "git", data: true, what: "delete a state file of the old standalone core", where: f, apply: () => {
      unlinkSync(f);
      rmDirIfEmpty(dirname(f));
    } });
  }
  const local = join(root, ".github", "instructions", "ai-context-hub.instructions.md");
  if (isFile(local)) {
    if (isTracked(".github/instructions/ai-context-hub.instructions.md")) out.kept.push(`${local}: tracked by git, so it is the team's copy`);
    else if (withoutBlock(read(local)) !== null) add({ group: "Per-repo leftovers", client: "git", what: "delete the local Hub instructions file", where: local, apply: () => {
      unlinkSync(local);
      rmDirIfEmpty(dirname(local));
    } });
  }
  for (const rel of ["AGENTS.md", ".github/copilot-instructions.md"]) {
    const f = join(root, rel);
    if (isFile(f) && read(f).includes(BLOCK_START)) out.kept.push(`${f}: holds a Hub block; ${isTracked(rel) ? "git tracks the file, so it is the team's" : "remove the block by hand if you want it gone (the file is yours)"}`);
  }
  const exclude = gitPath(root, "info/exclude");
  if (exclude && isFile(exclude)) {
    const cut = cleanExclude(read(exclude));
    if (cut.removed.length) add({ group: "Per-repo leftovers", client: "git", what: `remove ${cut.removed.length} Hub line(s) from info/exclude`, where: exclude, apply: () => writeFileSync(exclude, cleanExclude(read(exclude)).text, "utf8") });
  }
  const hooksDir = gitPath(root, "hooks");
  for (const spec of [PRE_COMMIT, PRE_PUSH]) {
    const hook = join(hooksDir, spec.hook);
    if (!hooksDir || !isFile(hook) || stripHookBlock(read(hook), spec.begin, spec.end) === null) continue;
    const chained = join(hooksDir, spec.chained);
    add({ group: "Per-repo leftovers", client: "git", what: `remove the Hub block from the ${spec.hook} hook${isFile(chained) ? ` and restore your own hook from ${spec.chained}` : ""}`, where: hook, apply: () => {
      const rest = stripHookBlock(read(hook).replace(/\r\n/g, "\n"), spec.begin, spec.end) ?? "";
      const empty = rest.replace(/^#!.*\n?/, "").trim() === "";
      if (!empty) return void writeFileSync(hook, rest, "utf8");
      unlinkSync(hook);
      if (isFile(chained)) renameSync(chained, hook);
    } });
  }
  const gitDir = git(root, ["rev-parse", "--git-dir"]);
  const port = gitDir ? join(resolve(root, gitDir), "aihub-port") : "";
  if (port && isFile(port)) add({ group: "Per-repo leftovers", client: "git", what: "delete the Hub port file", where: port, apply: () => unlinkSync(port) });
}

